import { URL } from "node:url";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import { runInNewContext } from "node:vm";
import console from "node:console";
const source = readFileSync(new URL("./src/features/settings/validation.ts", import.meta.url), "utf8");
const exports = {};
runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports });
const { validateContact, validatePassword } = exports;
assert.equal(validateContact("Minh Anh", "minh@example.com", "+84 912 345 678", ""), "");
assert.ok(validateContact("", "minh@example.com", "", ""));
assert.ok(validateContact("Minh Anh", "bad", "", ""));
assert.ok(validateContact("Minh Anh", "minh@example.com", "--------", ""));
assert.ok(validateContact("Minh Anh", "minh@example.com", "", "bad"));
assert.equal(Object.keys(validatePassword("old-pass", "new-pass", "new-pass")).length, 0);
assert.ok(validatePassword("", "new-pass", "new-pass").current);
assert.ok(validatePassword("old-pass", "short", "short").password);
assert.ok(validatePassword("old-pass", "old-pass", "old-pass").password);
assert.ok(validatePassword("old-pass", "new-pass", "different").confirmation);
console.log("Account settings validation checks passed.");
